import fs from "node:fs";
import { execFileSync } from "node:child_process";

const output = "docs/project-structure.md";
if (!fs.existsSync(output)) fs.writeFileSync(output, "");
// Git's exclusions protect credentials and keep local client archives out of this inventory.
const files = execFileSync("git", ["ls-files", "--cached", "--others", "--exclude-standard", "-z"], { encoding: "utf8" })
  .split("\0").filter(file => file && fs.existsSync(file) && fs.statSync(file).isFile()).sort();
const tree = new Map();
for (const file of files) {
  let branch = tree;
  for (const segment of file.split("/")) {
    if (!branch.has(segment)) branch.set(segment, new Map());
    branch = branch.get(segment);
  }
}
const lines = ["apar-one-front/"];
function render(branch, prefix = "") {
  const entries = [...branch.entries()].sort(([a, av], [b, bv]) =>
    Number(bv.size > 0) - Number(av.size > 0) || a.localeCompare(b));
  entries.forEach(([name, children], i) => {
    const last = i === entries.length - 1;
    lines.push(`${prefix}${last ? "└── " : "├── "}${name}${children.size ? "/" : ""}`);
    if (children.size) render(children, prefix + (last ? "    " : "│   "));
  });
}
render(tree);
fs.writeFileSync(output, `# Project folder and file tree\n\nGenerated by \`npm run docs:tree\`. Includes every maintained source, configuration, documentation, test and shipped asset file (${files.length} files).\n\nExcluded: \`node_modules/\`, \`.next/\`, \`.git/\`, local credentials, generated reports, OS files and the raw campaign folders listed in \`.gitignore\`. Those originals remain on disk; only selected exports under \`public/\` are served. \`design-source/\` contains preserved editable originals and unused fonts and is excluded from direct Vercel uploads.\n\n\`\`\`text\n${lines.join("\n")}\n\`\`\`\n`);
console.log(`Wrote ${output}: ${files.length} maintained files.`);
